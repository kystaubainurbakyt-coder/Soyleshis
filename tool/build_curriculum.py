"""Compile the editor's JSON catalog into a read-only Flutter curriculum."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / 'assets/curriculum/catalog.json'
OUTPUT = ROOT / 'lib/features/lessons/data/curriculum_data.dart'

def validate(catalog):
    ids = set()
    for lesson in catalog:
        assert lesson['id'] not in ids, 'Duplicate lesson id'
        ids.add(lesson['id'])
        assert lesson['level'] in ['A1', 'A2', 'B1', 'B2', 'C1']
        for field in ['title', 'rule']:
            for lang in (['kk', 'ru', 'en'] if field == 'title' else ['ru', 'en']):
                assert len(lesson[field][lang].strip()) >= (70 if field == 'rule' else 3), f'Incomplete {field}'
        assert len(lesson['phrases']) >= 6
        for phrase in lesson['phrases']:
            assert all(phrase[lang].strip() for lang in ['kk', 'ru', 'en'])
        for lang in ['kk', 'ru', 'en']:
            assert len({p[lang] for p in lesson['phrases']}) == len(lesson['phrases']), 'Duplicate answer in lesson'

def compile_catalog(catalog, output=OUTPUT):
    validate(catalog)
    output.parent.mkdir(parents=True, exist_ok=True)
    text = json.dumps(catalog, ensure_ascii=False, indent=2).replace('$', r'\$')
    output.write_text('// Generated by tool/build_curriculum.py. Edit assets/curriculum/catalog.json.\nconst curriculumData = <Map<String, dynamic>>' + text + ';\n', encoding='utf-8')

def import_source():
    result = []
    for block in (ROOT / 'tool/curriculum_source.txt').read_text(encoding='utf-8').strip().split('\n\n'):
        lines = block.strip().splitlines()
        level, identity, kk, ru, en, rule_ru, rule_en = lines[0].split('|')
        phrases = [dict(zip(['kk', 'ru', 'en'], row.split('~'))) for row in lines[1:]]
        result.append({'id': int(identity), 'level': level, 'title': {'kk': kk, 'ru': ru, 'en': en},
            'rule': {'ru': rule_ru, 'en': rule_en}, 'phrases': phrases,
            'minutes': {'A1': 18, 'A2': 22, 'B1': 25, 'B2': 28, 'C1': 32}[level]})
    return result

if __name__ == '__main__':
    import sys
    data = import_source() if '--import-source' in sys.argv else json.loads(CATALOG.read_text(encoding='utf-8'))
    validate(data)
    CATALOG.parent.mkdir(parents=True, exist_ok=True)
    CATALOG.write_text(json.dumps(data, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    compile_catalog(data)
    print({level: sum(l['level'] == level for l in data) for level in ['A1', 'A2', 'B1', 'B2', 'C1']})
